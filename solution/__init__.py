"""Your solution.

The harness imports this package and calls `apply()` once, in the same process as `soup train`,
before Soup builds the model and the trainer. Patch whatever you need (transformers, peft,
bitsandbytes, Soup itself) so the training run uses your Triton kernels.

The rules in short (the README and the task statement have the full ones):
- your own `@triton.jit` kernels, defined in this folder, run in every measured run and together
  take >= 5% of the training time; the example's kernels (however renamed or rewritten) and
  kernels generated by torch.compile do not count;
- no ready-made kernel libraries (unsloth, liger-kernel, xformers, flash-attn, torchao, ...);
- the task stays the same: model, data, batches and their order, steps, LoRA, optimizer, Soup's
  settings and outputs; no other GPU, no background processes, no tricks with the measurement.
"""

from .add_rmsnorm import patch_qwen2_add_rmsnorm
from .head_patch import patch_causal_lm, patch_sft_trainer, patch_soup_setup
from .mlp import patch_qwen2_mlp_fp16
from .nf4 import patch_bnb_matmul_4bit
from .rmsnorm import patch_qwen2_rmsnorm
from .rope import patch_qwen2_rope
from .startup import patch_soup_row_mapping
from .swiglu import patch_qwen2_mlp
from .unpad import patch_qwen2_unpad
from .warmup import start as start_kernel_warmup


def apply():
    patch_soup_row_mapping()  # Soup's dataset map with a given fingerprint: no 2 s dill hash
    patch_qwen2_mlp()  # the example: works out of the box, does not count as your own kernel
    patch_qwen2_mlp_fp16()  # the MLP around it on the fp16 path: half the saved activations
    patch_qwen2_rmsnorm()  # ours: fused RMSNorm forward + backward
    patch_qwen2_add_rmsnorm()  # ours: residual add + post-attention RMSNorm in one kernel
    patch_qwen2_unpad()  # decoder layers on real tokens only (after add_rmsnorm: wraps its layer)
    patch_qwen2_rope()  # ours: fused rotary embedding for q and k, forward + backward
    patch_causal_lm()  # ours: lm_head + cross-entropy + entropy/accuracy without full logits
    patch_sft_trainer()  # logs TRL's metrics and Soup's rewind losses from the fused step
    patch_soup_setup()  # tied embedding / lm_head kept in fp16 (same values), -933 MB
    patch_bnb_matmul_4bit()  # ours: one-launch NF4 dequantization for every 4-bit layer
    start_kernel_warmup()  # compile the kernels in the background while Soup loads the model
